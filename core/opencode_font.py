def build_text_grid(text: str, split_index: Optional[int] = None) -> List[List[Tuple[int, int, int]]]:
    """
    Renders any text into an 8-row OpenCode pixel matrix.
    Colors are automatically split into two halves (Gray + White).
    """
    if split_index is None:
        split_index = len(text) // 2

    # Map each character to colored blocks
    colored_chars = []
    for idx, ch in enumerate(text):
        glyph = _GLYPHS.get(ch, _GLYPHS.get(ch.lower(), _GLYPHS.get(ch.upper(), _GLYPHS[' '])))
        
        # Determine color for this character
        if idx < split_index:
            c_main = GRAY
            c_shadow = GRAY_SHADOW
        else:
            c_main = WHITE
            c_shadow = WHITE_SHADOW
            
        char_grid = []
        for r in range(8):
            row = []
            for val in glyph[r]:
                if val == 0:
                    row.append(BG)
                elif val == 1:
                    row.append(c_main)
                elif val == 2:
                    row.append(c_shadow)
            char_grid.append(row)
        colored_chars.append(char_grid)

    # Combine into full grid with 1-unit spacing between letters
    grid = []
    for r in range(8):
        row = []
        for idx, ch_grid in enumerate(colored_chars):
            if idx > 0:
                row.append(BG) # 1 unit letter spacing
            row.extend(ch_grid[r])
        grid.append(row)

    return grid


def render_opencode_image(text: str, scale: int = 18, bg_color: Tuple[int, int, int] = BG) -> Image.Image:
    """
    Draws the OpenCode text as a high-res PIL Image.
    Each unit pixel is scaled by `scale` pixels.
    """
    grid = build_text_grid(text)
    rows = len(grid)
    cols = len(grid[0]) if rows > 0 else 0

    img_w = cols * scale
    img_h = rows * scale

    im = Image.new("RGBA", (img_w, img_h), (*bg_color, 255) if bg_color else (0, 0, 0, 0))
    pixels = im.load()

    for r in range(rows):
        for c in range(cols):
            color = grid[r][c]
            if color == BG and bg_color is None:
                continue
            r_start = r * scale
            c_start = c * scale
            for y in range(r_start, r_start + scale):
                for x in range(c_start, c_start + scale):
                    pixels[x, y] = (*color, 255)

    return im


def generate_ansi_banner(text: str, user_name: str = "Developer", persona: str = "Creator & Coder", output_path: Optional[str] = None) -> str:
    """
    Generates a 24-bit TrueColor ANSI welcome banner for PowerShell/CMD.
    """
    grid = build_text_grid(text)
    rows = len(grid)
    cols = len(grid[0]) if rows > 0 else 0

    meta = [
        "",
        "",
        f"    \033[1;37m{text.lower()} cli\033[0m \033[90m(v2.0)\033[0m",
        f"    \033[90m{user_name} • {persona}\033[0m",
        f"    \033[90mSystem: Windows Terminal • Windows 11\033[0m",
        f"    \033[37m~\033[0m",
        "",
        ""
    ]

    lines = [""]
    for r in range(rows):
        row_str = "  "
        for c in range(cols):
            col = grid[r][c]
            if col == BG:
                row_str += "  "
            else:
                row_str += f"\033[38;2;{col[0]};{col[1]};{col[2]}m██\033[0m"
        if r < len(meta):
            row_str += meta[r]
        lines.append(row_str)

    lines.append("")
    full_ansi = "\n".join(lines)

    if output_path:
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(full_ansi)

    return full_ansi
